// Concierge for Home Assistant – Service Worker
// Kein Caching, keine Offline-Unterstützung (per Spec nicht erforderlich).
// Existiert ausschließlich damit der Browser Concierge als installierbare PWA erkennt.

self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (e) => e.waitUntil(self.clients.claim()));
self.addEventListener("fetch", (e) => e.respondWith(fetch(e.request)));
